import { expect, test } from '@playwright/test';
import { prisma } from '@sparki/db';

test.use({ timezoneId: 'America/Chicago' });

const API_URL = process.env.API_URL ?? 'http://127.0.0.1:4000';
// The runner owns and removes the entire disposable database for this spec.
test('SPA-7 UI handoff, reviewed discharge persistence, record resume and checkout attestation', async ({ page, request }) => {
  test.setTimeout(180000);
  page.setDefaultTimeout(15000);
  const hydrationErrors: string[] = [];
  page.on('pageerror', (error) => { if (/hydration|hydrated|#418/i.test(error.message)) hydrationErrors.push(error.message); });
  const clientResponse = await request.post(`${API_URL}/clients`, { data: { firstName: 'SPA7', lastName: 'Synthetic Client', phone: '312-555-0199', email: 'spa7@example.test' } });
  expect(clientResponse.ok()).toBeTruthy();
  const client = await clientResponse.json();
  const patientResponse = await request.post(`${API_URL}/patients`, { data: { name: 'SPA7 Synthetic Patient', species: 'Canine', clients: [{ clientId: client.id, isPrimary: true }] } });
  expect(patientResponse.ok()).toBeTruthy();
  const patient = await patientResponse.json();
  const created = await request.post(`${API_URL}/visits`, { data: { patientId: patient.id, reason: 'Synthetic workflow verification', primaryVeterinarianId: 'dev-user' } });
  expect(created.ok()).toBeTruthy();
  const visit = await created.json();
  await prisma.catalogItem.create({ data: { organizationId: 'dev-organization', locationId: 'dev-location', name: 'SPA7 QA service', primaryType: 'SERVICE', billable: true, retailPrice: 1 } });
  await page.goto(`/visits/${visit.id}`);
  await page.getByRole('button', { name: 'Begin Intake', exact: true }).click();
  await page.locator('#weight').fill('22');
  await page.locator('#temperature').fill('101');
  await page.locator('#heartRate').fill('90');
  await page.locator('#respiratoryRate').fill('20');
  await page.locator('#crtSeconds').fill('1');
  await page.locator('#gumColor').selectOption('Pink');
  await page.locator('#historyNotes').fill('Synthetic intake history for record context.');
  await page.getByRole('button', { name: 'Ready for Veterinarian' }).click();
  await page.getByRole('button', { name: 'Start exam', exact: true }).click();
  await expect(page.getByText('Step 1 of 5 · Exam')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Normal', exact: true }).first()).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', { name: 'Not examined', exact: true }).nth(1).click();
  await page.getByLabel('Diagnoses', { exact: true }).fill('Synthetic assessment');
  await page.getByLabel('Diagnoses', { exact: true }).press('Enter');
  await page.getByLabel('Treatment Plan', { exact: true }).fill('INTERNAL_EXAM_MARKER');
  await page.getByLabel("What's Next", { exact: true }).fill('INTERNAL_FOLLOWUP_MARKER');
  await page.getByRole('button', { name: 'Continue to treatment plan →' }).click();
  await page.locator('select[name="type"]').selectOption('Diagnostic');
  await page.getByLabel('Diagnostic name').fill('Synthetic diagnostic');
  await page.getByLabel('Plan details', { exact: true }).fill('STAFF_ONLY_TASK_1004');
  await page.getByRole('button', { name: 'Add to treatment plan' }).click();
  await expect(page.getByText('Synthetic diagnostic', { exact: true }).first()).toBeVisible();
  await page.getByRole('button', { name: 'Continue to care →' }).click();
  await page.getByText('Record test performed', { exact: true }).click();
  await page.getByRole('button', { name: 'Mark test performed' }).click();
  await expect(page.getByRole('button', { name: 'Continue to discharge →' })).toBeEnabled();
  await page.getByRole('button', { name: 'Continue to discharge →' }).click();
  await expect(page.locator('textarea[name="instructions"]')).toHaveValue('');
  await expect(page.getByRole('button', { name: 'Continue to review →' })).toBeDisabled();
  await page.locator('.visit-discharge-guidance summary').click();
  await page.locator('textarea[name="visitSummary"]').fill('CLIENT_SUMMARY: synthetic reviewed visit summary.');
  await page.locator('textarea[name="diet"]').fill('CLIENT_DIET: synthetic feeding instructions.');
  await page.locator('textarea[name="activity"]').fill('CLIENT_ACTIVITY: synthetic activity guidance.');
  await page.locator('textarea[name="urgentSigns"]').fill('CLIENT_URGENT: synthetic urgent-care guidance.');
  await page.locator('textarea[name="emergencyContact"]').fill('CLIENT_ER: example emergency hospital 312-555-0198');
  await page.locator('.visit-discharge-followup-panel summary').click();
  await page.locator('input[name="recheckDate"]').fill('2026-10-12');
  await expect(page.locator('textarea[name="medicationInstructions"]')).toHaveCount(0);
  await page.getByRole('button', { name: 'Add medication', exact: true }).click();
  await page.locator('textarea[name="instructions"]').fill('CLIENT_HOME_V1: synthetic home-care instructions.');
  await expect(page.getByRole('button', { name: 'Continue to review →' })).toBeDisabled();
  const medication = page.getByRole('group', { name: /New medication|CLIENT_MEDICATION: synthetic only/, exact: true });
  for (const [name, value] of [['Medication', 'CLIENT_MEDICATION: synthetic only'], ['Dose', 'CLIENT_DOSE'], ['Route', 'CLIENT_ROUTE'], ['Frequency', 'CLIENT_FREQUENCY'], ['Duration', 'CLIENT_DURATION'], ['Next dose (optional)', 'CLIENT_NEXT_DOSE'], ['Special instructions (optional)', 'CLIENT_SPECIAL']] as const) await medication.getByRole(name === 'Medication' ? 'combobox' : 'textbox', { name, exact: true }).fill(value);
  await medication.getByRole('button', { name: 'Add', exact: true }).click();
  await expect(medication.getByRole('combobox', { name: 'Medication', exact: true })).toBeHidden();
  await medication.getByRole('button', { name: 'Edit', exact: true }).click();
  await expect(medication.getByRole('combobox', { name: 'Medication', exact: true })).toHaveValue('CLIENT_MEDICATION: synthetic only');
  await expect(page.getByRole('button', { name: 'Add medication', exact: true })).toHaveCount(0);
  await medication.getByRole('button', { name: 'Add', exact: true }).click();
  await page.getByRole('button', { name: 'Add medication', exact: true }).click();
  await page.getByRole('button', { name: 'Remove new medication', exact: true }).click();
  await page.locator('.visit-discharge-extra-directions summary').click();
  await page.locator('textarea[name="medicationInstructions"]').fill('CLIENT_MED: synthetic directions for layout testing only.');
  await page.locator('textarea[name="warningSigns"]').fill('CLIENT_WARNING: synthetic warning instructions.');
  await page.locator('textarea[name="followUpPlan"]').fill('CLIENT_FOLLOWUP: arrange synthetic recheck.');
  await page.getByLabel('Ask reception to schedule').check();
  await page.getByRole('button', { name: 'Continue to review →' }).click();
  await expect(page.getByRole('heading', { name: 'Medical record', exact: true })).toBeVisible();
  await expect(page.getByRole('textbox', { name: 'Subjective', exact: true })).toHaveValue(/Synthetic intake history/, { timeout: 15000 });
  await expect(page.getByRole('textbox', { name: 'Objective', exact: true })).toHaveValue(/Weight: 22/, { timeout: 15000 });
  await page.goto(`/visits/${visit.id}?resume=visit-record`);
  await expect(page.getByRole('heading', { name: 'Medical record', exact: true })).toBeVisible();
  await page.context().addCookies([{ name: 'sparki_session', value: 'dev:staff-test-technician', domain: '127.0.0.1', path: '/' }]);
  await page.goto(`/visits/${visit.id}?view=discharge`);
  await expect(page.locator('textarea[name="instructions"]')).toHaveValue('CLIENT_HOME_V1: synthetic home-care instructions.');
  await page.locator('textarea[name="instructions"]').fill('');
  await expect(page.getByRole('button', { name: 'Continue to review →' })).toBeDisabled();
  await page.locator('textarea[name="instructions"]').fill('CLIENT_HOME_V2: revised synthetic home care.');
  await expect(page.locator('textarea[name="instructions"]')).toHaveValue('CLIENT_HOME_V2: revised synthetic home care.');
  await expect(page.getByRole('button', { name: 'Download PDF' })).toHaveCount(0);
  await page.getByRole('button', { name: 'Continue to review →' }).click();
  await expect(page.getByRole('heading', { name: 'Medical record', exact: true })).toBeVisible();
  await page.context().addCookies([{ name: 'sparki_session', value: 'dev:staff-test-veterinarian', domain: '127.0.0.1', path: '/' }]);
  await page.goto(`/visits/${visit.id}?view=discharge`);
  await expect(page.locator('textarea[name="instructions"]')).toHaveValue('CLIENT_HOME_V2: revised synthetic home care.');
  await expect(page.locator('#visit-discharge').getByRole('status')).toContainText('Saved');
  await page.getByRole('button', { name: 'Preview / PDF', exact: true }).click();
  await expect(page.getByRole('img', { name: 'Discharge PDF page 1', exact: false })).toBeVisible();
  await expect(page.locator('textarea[name="warningSigns"]')).toHaveValue('CLIENT_WARNING: synthetic warning instructions.');
  await expect(page.locator('textarea[name="visitSummary"]')).toHaveValue('CLIENT_SUMMARY: synthetic reviewed visit summary.');
  await expect(page.locator('input[name="medications.0.nextDose"]')).toHaveValue('CLIENT_NEXT_DOSE');
  await expect(page.locator('input[name="recheckDate"]')).toHaveValue('2026-10-12');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download PDF' }).click();
  const download = await downloadPromise;
  expect(await download.failure()).toBeNull();
  await download.saveAs(test.info().outputPath('client-discharge.pdf'));
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Discharge PDF' })).not.toBeVisible();
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.screenshot({ path: test.info().outputPath('discharge-desktop.png'), fullPage: true });
  await page.getByRole('heading', { name: 'Discharge', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: test.info().outputPath('discharge-editor-top.png') });
  await page.getByRole('group', { name: /New medication|CLIENT_MEDICATION: synthetic only/, exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: test.info().outputPath('discharge-medication-editor.png') });
  await page.setViewportSize({ width: 1024, height: 768 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
  await page.screenshot({ path: test.info().outputPath('discharge-tablet.png'), fullPage: true });
  await page.goto(`/visits/${visit.id}?resume=visit-record`);
  await expect(page.getByText('Only the assigned clinician', { exact: false })).toBeVisible();
  await page.context().addCookies([{ name: 'sparki_session', value: 'dev:staff-test-receptionist', domain: '127.0.0.1', path: '/' }]);
  await page.route('**/api/inventory/items?search=*', async (route) => {
    if (!new URL(route.request().url()).searchParams.get('search')) {
      const response = await route.fetch();
      await new Promise((resolve) => setTimeout(resolve, 700));
      await route.fulfill({ response });
    } else await route.continue();
  });
  await page.goto(`/visits/${visit.id}?view=checkout`);
  await page.getByLabel('Add a service or item').fill('SPA7 QA service');
  await page.getByRole('button', { name: /SPA7 QA service/ }).first().click();
  await page.getByRole('button', { name: 'Continue to payment →' }).click();
  await page.getByRole('button', { name: 'Other', exact: true }).click();
  await page.getByRole('button', { name: 'Record payment', exact: true }).click();
  await page.getByLabel('Client contact details confirmed').check();
  await page.getByRole('button', { name: 'Finish checkout', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Visit checkout is complete' })).toBeVisible();
  await page.reload();
  await expect(page.getByLabel('Client contact details confirmed')).toBeChecked();
  await expect(page.getByLabel('Client contact details confirmed')).toBeDisabled();
  await expect(page.getByText(/312-555-0199/)).toBeVisible();
  await page.context().addCookies([{ name: 'sparki_session', value: 'dev:dev-user', domain: '127.0.0.1', path: '/' }]);
  await page.goto(`/visits/${visit.id}?resume=visit-record`);
  await page.getByRole('button', { name: 'Finalize visit', exact: true }).click();
  await expect(page).toHaveURL('/');
  await page.goto(`/visits/${visit.id}?view=record`);
  await expect(page.getByText('Visit complete — record signed and patient checked out.')).toBeVisible();
  const canonical = await prisma.visit.findUniqueOrThrow({ where: { id: visit.id }, include: { discharge: true, checkout: true, invoice: { include: { lines: true, payments: true } }, soapNotes: true, examFindings: true } });
  expect(canonical.discharge?.completedById).toBe('staff-test-technician');
  expect(canonical.checkout?.completedById).toBe('staff-test-receptionist');
  expect(canonical.discharge?.instructions).toContain('CLIENT_HOME_V2');
  expect(JSON.stringify(canonical.discharge)).not.toContain('STAFF_ONLY');
  expect(JSON.stringify(canonical.discharge)).not.toContain('INTERNAL_');
  expect(canonical.discharge?.clientGuidance).toMatchObject({ urgentSigns: 'CLIENT_URGENT: synthetic urgent-care guidance.' });
  expect(canonical.discharge?.clientGuidance).toMatchObject({ visitSummary: 'CLIENT_SUMMARY: synthetic reviewed visit summary.', recheckDate: '2026-10-12', medications: [expect.objectContaining({ nextDose: 'CLIENT_NEXT_DOSE' })] });
  expect(canonical.discharge?.instructions).not.toContain('STAFF_ONLY');
  expect(canonical.checkout?.clientContactConfirmed).toBe(true);
  expect(canonical.invoice?.lines).toHaveLength(1);
  expect(canonical.invoice?.payments).toHaveLength(1);
  expect(canonical.invoice?.status).toBe('PAID');
  expect(canonical.invoice?.payments[0]?.amountCents).toBe(100);
  expect(canonical.invoice?.lines[0]?.totalAmountCents).toBe(100);
  expect(canonical.soapNotes[0]?.status).toBe('Locked');
  expect(canonical.state).toBe('Archived');
  const findings = JSON.parse(canonical.examFindings?.objective ?? '{}');
  expect(findings.systems.eyes.status).toBe('Normal');
  expect(findings.systems.ears.status).toBe('Not examined');
  expect(findings.systems.ears.documented).toBe(true);
  expect(findings.systems.noseThroat.status).toBe('Normal');
  await page.goto(`/visits/${visit.id}?view=discharge`);
  await page.getByRole('button', { name: 'Preview / PDF', exact: true }).click();
  await expect(page.locator('textarea[name="instructions"]')).toHaveCount(0);
  await page.goto(`/patients/${patient.id}`);
  await expect(page.getByRole('heading', { name: patient.name, exact: true }).first()).toBeVisible();
  expect(hydrationErrors).toEqual([]);
});
